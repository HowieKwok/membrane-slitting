            hTuplePointX = 0;
            hTuplePointY = 0;

            HObject ho_Cross;
            HObject ho_Contour;
            HOperatorSet.GenEmptyObj(out ho_Cross);
            HOperatorSet.GenEmptyObj(out ho_Contour);

            try
            {
                if (hv_pos)//水平
                {
                    phi = 3.1415 / 2;
                }
                else
                {

                }

