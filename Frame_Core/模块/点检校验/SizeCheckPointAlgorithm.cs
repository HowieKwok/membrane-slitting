        /// <summary>
        /// 计算系数
        /// </summary>
        public bool CalculateCoefficient(HObject ho_Image1, HWindow HalconWinHandle, HTuple row, HTuple col, HTuple phi, HTuple len1, HTuple len2, HTuple Checkerboard_W,
            out double A, out double B, out double C, out double D)
        {
            HTuple hv_Width = new HTuple(), hv_Height = new HTuple();

            HTuple hv_Row1 = new HTuple(), hv_Row2 = new HTuple();
            HTuple hv_Column1 = new HTuple(), hv_Column2 = new HTuple();
            HTuple hv_TmpCtrl_Row = new HTuple(), hv_TmpCtrl_Column = new HTuple(), hv_TmpCtrl_Phi = new HTuple(), hv_TmpCtrl_Len1 = new HTuple(), hv_TmpCtrl_Len2 = new HTuple();
            HTuple hv_TmpCtrl_Dr = new HTuple(), hv_TmpCtrl_Dc = new HTuple();
            HTuple hv_AmplitudeThreshold = 40, hv_RoiWidthLen2 = 5;
            HTuple hv_MsrHandle_Measure_01_0 = new HTuple();
            HTuple hv_Row_Measure_01_0 = new HTuple(), hv_Column_Measure_01_0 = new HTuple(), hv_Amplitude_Measure_01_0 = new HTuple(), hv_Distance_Measure_01_0 = new HTuple();
            HTuple hv_Length = new HTuple();
            HTuple hv_X = new HTuple(), hv_Y = new HTuple();

            HObject ho_RegionLines;
            HObject ho_Region;
            HObject ho_Cross;
            HObject ho_Contour;
            HOperatorSet.GenEmptyObj(out ho_RegionLines);
            HOperatorSet.GenEmptyObj(out ho_Region);
            HOperatorSet.GenEmptyObj(out ho_Cross);
            HOperatorSet.GenEmptyObj(out ho_Contour);
            A = 0;
            B = 0;
            C = 0;
            D = 0;
            bool result = true;
            try
            {

                //Measure 01: Code generated by Measure 01
                //Measure 01: Prepare measurement
                // stop(...); only in hdevelop      

                HOperatorSet.GenRegionLine(out ho_RegionLines, hv_Row1, hv_Column1, hv_Row2, hv_Column2);
                HOperatorSet.SetSystem("int_zooming", "true");

                //hv_TmpCtrl_Row = 0.5 * (Line_Row1 + Line_Row2);
                //hv_TmpCtrl_Column = 0.5 * (Line_Col1 + Line_Col2);
                //hv_TmpCtrl_Dr = Line_Row1 - Line_Row2;
                //hv_TmpCtrl_Dc = Line_Col2 - Line_Col1;
                //hv_TmpCtrl_Phi = 0;
                //hv_TmpCtrl_Len1 = 0.5 * ((((hv_TmpCtrl_Dr * hv_TmpCtrl_Dr) + (hv_TmpCtrl_Dc * hv_TmpCtrl_Dc))).TupleSqrt());
                //hv_TmpCtrl_Len2 = hv_RoiWidthLen2;

                hv_TmpCtrl_Row = row;
                hv_TmpCtrl_Column = col;
                hv_TmpCtrl_Phi = 0;
                hv_TmpCtrl_Len1 = len1;
                hv_TmpCtrl_Len2 = hv_RoiWidthLen2;

                //Measure 01: Create measure for line Measure 01 [0]
                //Measure 01: Attention: This assumes all images have the same size!
                HOperatorSet.GetImageSize(ho_Image1, out hv_Width, out hv_Height);
                hv_MsrHandle_Measure_01_0.Dispose();
                HOperatorSet.GenMeasureRectangle2(hv_TmpCtrl_Row, hv_TmpCtrl_Column, hv_TmpCtrl_Phi,
                    hv_TmpCtrl_Len1, hv_TmpCtrl_Len2, hv_Width, hv_Height, "nearest_neighbor",
                    out hv_MsrHandle_Measure_01_0);
                //Measure 01: ***************************************************************
                //Measure 01: * The code which follows is to be executed once / measurement *
                //Measure 01: ***************************************************************
                //Measure 01: The image is assumed to be made available in the
                //Measure 01: variable last displayed in the graphics window

                //Measure 01: Execute measurements

                hv_Row_Measure_01_0.Dispose(); hv_Column_Measure_01_0.Dispose(); hv_Amplitude_Measure_01_0.Dispose(); hv_Distance_Measure_01_0.Dispose();
                HOperatorSet.MeasurePos(ho_Image1, hv_MsrHandle_Measure_01_0, 1, hv_AmplitudeThreshold,
                    "all", "all", out hv_Row_Measure_01_0, out hv_Column_Measure_01_0, out hv_Amplitude_Measure_01_0,
                    out hv_Distance_Measure_01_0);
                ho_Region.Dispose();
                HOperatorSet.GenRegionPoints(out ho_Region, hv_Row_Measure_01_0, hv_Column_Measure_01_0);

                ho_Cross.Dispose();
                HOperatorSet.SetColor(HalconWinHandle, "forest green");
                HOperatorSet.GenCrossContourXld(out ho_Cross, hv_Row_Measure_01_0, hv_Column_Measure_01_0, 200, 0.785398);
                //HOperatorSet.DispObj(ho_Cross, HalconWinHandle);

                //Measure 01: Do something with the results
                //Measure 01: Clear measure when done
                HOperatorSet.CloseMeasure(hv_MsrHandle_Measure_01_0);

                hv_Length.Dispose();
                HOperatorSet.TupleLength(hv_Column_Measure_01_0, out hv_Length);

                //标尺坐标
                hv_Y.Dispose();
                hv_Y = HTuple.TupleGenSequence(0, (hv_Length * Checkerboard_W) - 1, Checkerboard_W);


                //图像列坐标
                hv_X.Dispose();
                hv_X = new HTuple(hv_Column_Measure_01_0);

                //将坐标点变成十字架图标
                ho_Cross.Dispose();
                HOperatorSet.GenCrossContourXld(out ho_Cross, hv_Y, hv_X, 200, 0.785398);
                //HOperatorSet.DispObj(ho_Cross, HalconWinHandle);


                //% 现在将生成的点进行二次曲线拟合：Y = a*x^3 + b*x^3 + c*x + d

                //*转化为： XA = Y
                //      X = [X^3，X^2, X, 1],
                //      A = [a, b, c，d]
                //     Y
                //*
                HTuple hv_MatrixA = new HTuple(), hv_MatrixACol1 = new HTuple(), hv_MatrixACol0 = new HTuple(), hv_MatrixACol2 = new HTuple();

                hv_MatrixA.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 4, 1.0, out hv_MatrixA);

                //创建|x|行4列，值为1.0的矩阵   X :=


                hv_MatrixACol1.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 1, hv_Y, out hv_MatrixACol1);

                //创建|x|行1列，值为x的矩阵,Y := [0:10:Size]


                hv_MatrixACol0.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 1, (hv_X * hv_X) * hv_X,
                    out hv_MatrixACol0);

                //创建|x|行1列，值为X * X * X的矩阵

                hv_MatrixACol1.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 1, hv_X * hv_X, out hv_MatrixACol1);

                //创建|x|行1列，值为X * X的矩阵

                hv_MatrixACol2.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 1, hv_X, out hv_MatrixACol2);

                //创建|x|行1列，值为X的矩阵
                HOperatorSet.SetSubMatrix(hv_MatrixA, hv_MatrixACol0, 0, 0);
                //用矩阵MatrixACol1来替换矩阵MatrixA中的0行0列中的值

                HOperatorSet.SetSubMatrix(hv_MatrixA, hv_MatrixACol1, 0, 1);
                //用矩阵MatrixACol0来替换矩阵MatrixA中的0行1列中的值（这里MatrixA是经过上一步变换之后的矩阵）
                HOperatorSet.SetSubMatrix(hv_MatrixA, hv_MatrixACol2, 0, 2);
                //用矩阵MatrixACol1来替换矩阵MatrixA中的0行2列中的值


                HTuple hv_MatrixB = new HTuple();
                hv_MatrixB.Dispose();
                HOperatorSet.CreateMatrix(new HTuple(hv_X.TupleLength()), 1, hv_Y, out hv_MatrixB);


                HTuple hv_MatrixX = new HTuple();
                hv_MatrixX.Dispose();
                HOperatorSet.SolveMatrix(hv_MatrixA, "general", 0, hv_MatrixB, out hv_MatrixX);
                //解方程即可得到a,b,c的系数，记为矩阵MatrixX

                //%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
                ///曲线拟合//

                HTuple hv_Sequence = HTuple.TupleGenSequence(0, hv_Width, 1);


                //该函数是得到矩阵MatrixX中0行0列的值
                HTuple hv_A = new HTuple();
                HTuple hv_B = new HTuple();
                HTuple hv_C = new HTuple();
                HTuple hv_D = new HTuple();
                hv_A.Dispose();
                HOperatorSet.GetValueMatrix(hv_MatrixX, 0, 0, out hv_A);
                hv_B.Dispose();
                HOperatorSet.GetValueMatrix(hv_MatrixX, 1, 0, out hv_B);
                hv_C.Dispose();
                HOperatorSet.GetValueMatrix(hv_MatrixX, 2, 0, out hv_C);
                hv_D.Dispose();
                HOperatorSet.GetValueMatrix(hv_MatrixX, 3, 0, out hv_D);
                //得到多项式的值
                HTuple hv_Distances = new HTuple();
                hv_Distances.Dispose();
                hv_Distances = ((((hv_A * hv_Sequence) * hv_Sequence) * hv_Sequence) + ((hv_B * hv_Sequence) * hv_Sequence)) + (hv_C * hv_Sequence);

                HTuple hv_xielv = new HTuple();
                hv_xielv.Dispose();
                hv_xielv = ((((3 * hv_A) * hv_Sequence) * hv_Sequence) + ((2 * hv_B) * hv_Sequence)) + hv_C;


                HTuple hv_SubDistance = new HTuple();
                hv_SubDistance.Dispose();
                HTuple end_val104 = hv_Width;
                HTuple step_val104 = 240;
                HTuple hv_Index;
                for (hv_Index = 0; hv_Index.Continue(end_val104, step_val104); hv_Index = hv_Index.TupleAdd(step_val104))
                {

                    HTuple ExpTmpLocalVar_SubDistance = hv_SubDistance.TupleConcat(
                        hv_Distances.TupleSelect(hv_Index));
                    hv_SubDistance.Dispose();
                    hv_SubDistance = ExpTmpLocalVar_SubDistance;


                }
                //% 将坐标点变成十字架图标。
                ho_Contour.Dispose();
                HOperatorSet.GenContourPolygonXld(out ho_Contour, hv_Distances, hv_Sequence);

                HOperatorSet.SetColor(HalconWinHandle, "forest green");

                //HOperatorSet.DispObj(ho_Contour, HalconWinHandle);

                A = hv_A.D;
                B = hv_B.D;
                C = hv_C.D;
                D = hv_D.D;

                //显示测量值
                for (int i = 0; i < hv_X.Length; i++)
                {
                    if (i > 0)
                    {
                        double DistancePP = GetWorldPerPoint(hv_X[i], A, B, C, D) - GetWorldPerPoint(hv_X[i - 1], A, B, C, D);
                        //HOperatorSet.SetFont(HalconWinHandle, "-Courier New-13-*-*-*-*-1-");
                        HOperatorSet.SetTposition(HalconWinHandle, hv_Row_Measure_01_0[i - 1] - 50, hv_X[i - 1] + 50);
                        HOperatorSet.WriteString(HalconWinHandle, "宽度：" + DistancePP.ToString("F2"));
                    }

                }

            }
            catch (Exception ex)
            {
                result = false;
                 Log4netRecord.ErrorLog.Debug(ex);

            }
            finally
            {
                ho_RegionLines.Dispose();
                ho_Region.Dispose();
                ho_Cross.Dispose();
                ho_Contour.Dispose();

            }

            return result;



        }

